#!/usr/bin/env python3
"""
Visualization Generator for Hadoop MapReduce Outputs
Reads pure output files generated by Hadoop jobs (from evidence/ or HDFS output)
Renders a rich Terminal Analytics Dashboard and exports a modern HTML5/SVG Visual Report.
Flow: Raw CSV -> HDFS -> MapReduce -> HDFS Output -> plot_results.py -> Visual Report
"""
import os
import sys

BASE_DIR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
EVIDENCE_DIR = os.path.join(BASE_DIR, "evidence")
DOCS_DIR = os.path.join(BASE_DIR, "docs")

def read_lines_safe(filepath):
    """Safely read lines handling utf-8, utf-16, or latin-1."""
    if not os.path.exists(filepath):
        return []
    for enc in ["utf-8-sig", "utf-16", "utf-8", "latin-1"]:
        try:
            with open(filepath, "r", encoding=enc) as f:
                return f.readlines()
        except UnicodeDecodeError:
            continue
    return []

def load_job01():
    """Reads Job 01: Order Status"""
    path = os.path.join(EVIDENCE_DIR, "job01_output.txt")
    data = {}
    for line in read_lines_safe(path):
        line = line.strip()
        if "\t" in line:
            k, v = line.split("\t", 1)
            if v.isdigit():
                data[k] = int(v)
    return data

def load_job02_monthly():
    """Reads Job 02: Monthly Revenue & Trend"""
    path = os.path.join(EVIDENCE_DIR, "job02_monthly_revenue_output.txt")
    records = []
    grand_total = None
    for line in read_lines_safe(path):
        parts = line.strip().split("\t")
        if len(parts) == 5:
            month, items, price, freight, val = parts
            try:
                row = {
                    "month": month,
                    "items": int(items),
                    "price": float(price),
                    "freight": float(freight),
                    "value": float(val)
                }
                if month == "ALL_TIME_TOTAL":
                    grand_total = row
                else:
                    records.append(row)
            except ValueError:
                continue
    return records, grand_total

def load_job03():
    """Reads Job 03: Category Analysis"""
    path = os.path.join(EVIDENCE_DIR, "job03_output.txt")
    records = []
    for line in read_lines_safe(path):
        parts = line.strip().split("\t")
        if len(parts) == 5:
            cat, items, price, freight, val = parts
            try:
                records.append({
                    "category": cat,
                    "items": int(items),
                    "price": float(price),
                    "freight": float(freight),
                    "value": float(val)
                })
            except ValueError:
                continue
    records.sort(key=lambda x: x["value"], reverse=True)
    return records

def load_job04():
    """Reads Job 04: Seller Performance"""
    path = os.path.join(EVIDENCE_DIR, "job04_output.txt")
    records = []
    for line in read_lines_safe(path):
        parts = line.strip().split("\t")
        if len(parts) == 5:
            s_id, items, price, freight, val = parts
            try:
                records.append({
                    "seller_id": s_id,
                    "items": int(items),
                    "price": float(price),
                    "freight": float(freight),
                    "value": float(val)
                })
            except ValueError:
                continue
    records.sort(key=lambda x: x["value"], reverse=True)
    return records

def load_job05():
    """Reads Job 05: Reviews Analysis"""
    path = os.path.join(EVIDENCE_DIR, "job05_reviews_output.txt")
    scores = {}
    avg_score = 0.0
    total_reviews = 0
    for line in read_lines_safe(path):
        line = line.strip()
        if "\t" in line:
            parts = line.split("\t")
            k = parts[0]
            if k.startswith("SCORE_") and len(parts) >= 2:
                scores[k.replace("SCORE_", "Star ")] = int(parts[1])
            elif k == "OVERALL_AVERAGE" and len(parts) >= 3:
                try:
                    avg_score = float(parts[1])
                    total_reviews = int(parts[2])
                except ValueError:
                    pass
    return scores, avg_score, total_reviews

def load_job06():
    """Reads Job 06: Delivery Logistics"""
    path = os.path.join(EVIDENCE_DIR, "job06_delivery_output.txt")
    metrics = {}
    for line in read_lines_safe(path):
        line = line.strip()
        if "\t" in line:
            k, v = line.split("\t", 1)
            metrics[k] = v
    return metrics

def print_terminal_dashboard():
    print("=" * 80)
    print(" HADOOP MAPREDUCE ANALYTICS DASHBOARD (OLIST DATASET)")
    print("=" * 80)

    # Job 1
    j1 = load_job01()
    total_orders = sum(j1.values())
    print("\n[JOB 01] ORDER STATUS DISTRIBUTION (Total: {:,} orders)".format(total_orders))
    for status, count in sorted(j1.items(), key=lambda x: x[1], reverse=True):
        pct = (count / total_orders) * 100 if total_orders else 0
        bar = "█" * int(pct / 2)
        print("  {:<15} : {:>7,} ({:>5.2f}%)  {}".format(status, count, pct, bar))

    # Job 2
    j2_records, j2_total = load_job02_monthly()
    if j2_records:
        tot_val = j2_total["value"] if j2_total else sum(r["value"] for r in j2_records)
        tot_it = j2_total["items"] if j2_total else sum(r["items"] for r in j2_records)
        print("\n[JOB 02] MONTHLY REVENUE & ORDER TREND (Total Platform: {:,.2f} R$ across {:,} items)".format(tot_val, tot_it))
        print("  {:<10} {:>10} {:>16} {:>16} {:>16}".format("Month", "Items Sold", "Price (R$)", "Freight (R$)", "Total (R$)"))
        print("  " + "-" * 74)
        for r in j2_records:
            print("  {:<10} {:>10,} {:>16,.2f} {:>16,.2f} {:>16,.2f}".format(
                r["month"], r["items"], r["price"], r["freight"], r["value"]
            ))

    # Job 3
    j3 = load_job03()
    print("\n[JOB 03] TOP 10 PRODUCT CATEGORIES BY REVENUE")
    print("  {:<30} {:>10} {:>15} {:>15}".format("Category", "Items Sold", "Price (R$)", "Total Val (R$)"))
    print("  " + "-" * 72)
    for r in j3[:10]:
        print("  {:<30} {:>10,} {:>15,.2f} {:>15,.2f}".format(
            r["category"][:30], r["items"], r["price"], r["value"]
        ))

    # Job 5
    scores, avg_sc, total_rev = load_job05()
    print("\n[JOB 05] CUSTOMER SATISFACTION (Avg: {:.2f} ⭐, Total: {:,} reviews)".format(avg_sc, total_rev))
    for star in ["Star 5", "Star 4", "Star 3", "Star 2", "Star 1"]:
        c = scores.get(star, 0)
        pct = (c / total_rev) * 100 if total_rev else 0
        bar = "★" * int(pct / 3)
        print("  {:<8} : {:>6,} ({:>5.2f}%)  {}".format(star, c, pct, bar))

    # Job 6
    j6 = load_job06()
    print("\n[JOB 06] DELIVERY LOGISTICS & DELAY ANALYSIS")
    print("  Delivered Orders with Dates : {:>10}".format(j6.get("total_delivered_orders", "N/A")))
    print("  Average Delivery Time       : {:>10} days".format(j6.get("avg_delivery_days", "N/A")))
    print("  Fastest Delivery (Min)      : {:>10} days".format(j6.get("min_delivery_days", "N/A")))
    print("  Slowest Delivery (Max)      : {:>10} days".format(j6.get("max_delivery_days", "N/A")))
    print("  On-Time Orders              : {:>10}".format(j6.get("on_time_orders", "N/A")))
    print("  Late Delivery Orders        : {:>10} (Rate: {})".format(
        j6.get("late_orders", "N/A"), j6.get("late_delivery_rate_pct", "N/A")
    ))
    print("=" * 80)

